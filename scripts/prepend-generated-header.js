import fs from 'node:fs';

const TARGET = new URL('../src/styles.css', import.meta.url);
const HEADER = '/* GENERATED by `npm run build:css` from src/tailwind.css — do not edit directly */\n';

const current = fs.readFileSync(TARGET, 'utf8');
if (!current.startsWith(HEADER)) {
  fs.writeFileSync(TARGET, HEADER + current);
}
